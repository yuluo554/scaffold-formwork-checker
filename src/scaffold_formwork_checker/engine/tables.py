class TableLookupError(ValueError):
    """查表失败：参数不在表域内（调用方按参数错误处置）。"""


def phi_of(lam):
    """λ → φ（表A.0.6）。λ=ceil 向上取整查离散档，禁插值；λ>250 用 φ=7320/λ²。"""
    if not (lam > 0):
        raise TableLookupError("长细比 λ 必须为正数，得到 %r" % (lam,))
    if lam <= 250.0:
        key = int(math.ceil(lam))
        return PHI_TABLE[key]
    return PHI_OVER_250_NUMERATOR / (lam * lam)


def _interp_1d(xs, ys, x):
    """一维线性插入（仅域内；xs 升序）。"""
    if x < xs[0] - 1e-9 or x > xs[-1] + 1e-9:
        raise TableLookupError("值 %r 超出表域 [%s, %s]" % (x, xs[0], xs[-1]))
    for i in range(len(xs) - 1):
        x0, x1 = xs[i], xs[i + 1]
        if x0 - 1e-9 <= x <= x1 + 1e-9:
            if x1 == x0:
                return ys[i]
            t = (x - x0) / (x1 - x0)
            return ys[i] + t * (ys[i + 1] - ys[i])
    return ys[-1]


def gk_of(h, la, rows="double"):
    """(步距 h, 纵距 la, 排数) → gk（表A.0.1，kN/m）。域内中间值按表注线性插入。"""
    if rows not in GK_TABLE:
        raise TableLookupError("脚手架排数须为 single/double，得到 %r" % (rows,))
    if not (h > 0 and la > 0):
        raise TableLookupError("步距/纵距必须为正数，得到 h=%r la=%r" % (h, la))
    table = GK_TABLE[rows]
    # 域边界（步距最小 1.2，纵距最小 1.2）
    if h < GK_H_ROWS[0] - 1e-9 or h > GK_H_ROWS[-1] + 1e-9:
        raise TableLookupError("步距 %r 超出表A.0.1 域 [%s, %s]" % (h, GK_H_ROWS[0], GK_H_ROWS[-1]))
    if la < GK_LA_COLS[0] - 1e-9 or la > GK_LA_COLS[-1] + 1e-9:
        raise TableLookupError("纵距 %r 超出表A.0.1 域 [%s, %s]" % (la, GK_LA_COLS[0], GK_LA_COLS[-1]))
    col_vals = [_interp_1d(list(GK_H_ROWS), [table[hh][la_key] for hh in GK_H_ROWS], h)
                for la_key in GK_LA_COLS]
    return _interp_1d(list(GK_LA_COLS), col_vals, la)


def mu_of(rows, wall_tie, lb):
    """(排数, 连墙件布置, 立杆横距 lb) → μ（表5.2.8，精确匹配，无插值）。"""
    if rows not in MU_TABLE:
        raise TableLookupError("脚手架排数须为 single/double，得到 %r" % (rows,))
    if wall_tie not in ("two_step_three_span", "three_step_three_span"):
        raise TableLookupError("连墙件布置须为 two_step_three_span/three_step_three_span，得到 %r" % (wall_tie,))
    table = MU_TABLE[rows]
    if rows == "single":
        if lb > 1.50 + 1e-9:
            raise TableLookupError("单排架立杆横距 ≤1.50m（表5.2.8），得到 %r" % (lb,))
        return table[1.50][wall_tie]
    # 双排：lb 精确匹配表档（1.05/1.30/1.55）
    for lb_key in sorted(table):
        if abs(lb - lb_key) < 1e-9:
            return table[lb_key][wall_tie]
    raise TableLookupError(
        "双排架立杆横距 %r 不在表5.2.8 离散档 %s 内（该表无插值注，须取表档值）"
        % (lb, sorted(table))
    )


def wind_phi_a05_of(h, la):
    """(步距 h, 纵距 la) → 敞开式挡风系数 φ（表A.0.5，精确匹配）。"""
    for h_key in A05_H_ROWS:
        if abs(h - h_key) < 1e-9:
            row = A05_WIND_PHI[h_key]
            for j, la_key in enumerate(A05_LA_COLS):
                if abs(la - la_key) < 1e-9:
                    return row[j]
            raise TableLookupError("纵距 %r 不在表A.0.5 列档 %s 内" % (la, list(A05_LA_COLS)))
    raise TableLookupError("步距 %r 不在表A.0.5 行档 %s 内" % (h, list(A05_H_ROWS)))


def verify_anchors():
    """转录锚点对账（thresholds.json 登记值 + 算例真值锚点）。任何不一致抛 AssertionError。"""
    # T-JGJ130-phi-table 锚点
    for lam, expect in ((80, 0.722), (100, 0.588), (150, 0.308), (200, 0.180), (250, 0.117)):
        assert PHI_TABLE[lam] == expect, ("phi", lam, PHI_TABLE[lam], expect)
    # 算例锚点（tests/test_examples_truth.py 同口径）
    for lam, expect in ((85, 0.692), (95, 0.626), (191, 0.197), (197, 0.186), (236, 0.131)):
        assert PHI_TABLE[lam] == expect, ("phi", lam, PHI_TABLE[lam], expect)
    # λ>250 表注公式
    assert abs(phi_of(260.0) - 7320.0 / (260.0 * 260.0)) < 1e-12
    # T-JGJ130-gk-table 锚点_双排
    gk_anchors = {
        (1.50, 1.5): 0.1444, (1.50, 1.8): 0.1552, (1.80, 1.5): 0.1295,
        (1.80, 1.8): 0.1389, (1.20, 1.2): 0.1538, (2.00, 2.1): 0.1394,
    }
    for (h, la), expect in gk_anchors.items():
        got = gk_of(h, la, "double")
        assert abs(got - expect) < 1e-9, ("gk", h, la, got, expect)
    # T-JGJ130-mu-coef 全表
    mu_anchors = {
        ("double", 1.05, "two_step_three_span"): 1.50,
        ("double", 1.05, "three_step_three_span"): 1.70,
        ("double", 1.30, "two_step_three_span"): 1.55,
        ("double", 1.30, "three_step_three_span"): 1.75,
        ("double", 1.55, "two_step_three_span"): 1.60,
        ("double", 1.55, "three_step_three_span"): 1.80,
        ("single", 1.50, "two_step_three_span"): 1.80,
        ("single", 1.50, "three_step_three_span"): 2.00,
    }
    for (rows, lb, tie), expect in mu_anchors.items():
        got = mu_of(rows, tie, lb)
        assert got == expect, ("mu", rows, lb, tie, got, expect)
    # 表A.0.5 算例锚点（EX-lizhigan-w-002：h=1.80/la=1.50 → 0.090）
    assert wind_phi_a05_of(1.8, 1.5) == 0.090, wind_phi_a05_of(1.8, 1.5)
    return True
